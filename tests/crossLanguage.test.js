import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { decryptGuestToken } from '../src/crypto/guestPayload.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const fixtures = join(root, 'integration', 'test-fixtures')

/**
 * If Python wrote python-tokens.json during pytest, verify JS decrypts them.
 * Otherwise skip gracefully so frontend CI still runs alone.
 */
describe('cross-language tokens from Python', () => {
  it('decrypts python-generated tokens when fixture exists', async () => {
    const key = JSON.parse(readFileSync(join(fixtures, 'fixture-key.json'), 'utf8')).encryptionKey
    const tokenPath = join(fixtures, 'python-tokens.json')
    let tokens
    try {
      tokens = JSON.parse(readFileSync(tokenPath, 'utf8'))
    } catch {
      // Generated by Python tests when the full suite runs
      expect(true).toBe(true)
      return
    }
    expect(tokens.length).toBeGreaterThan(0)
    for (const row of tokens) {
      const recovered = await decryptGuestToken(row.token, key)
      expect(recovered).toMatchObject(row.plaintext)
    }
  })
})